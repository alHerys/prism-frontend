import { test, expect } from '@playwright/test';

test('ten production component stories render and interactive examples work', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const story = async (name: string) => {
    await page.goto(`/iframe.html?id=prism-komponen--${name}&viewMode=story`);
    await expect(page.locator('#storybook-root')).not.toBeEmpty();
    await expect(page.locator('.sb-errordisplay')).not.toBeVisible();
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  };
  await story('tombol');
  await expect(page.getByRole('button', { name: 'Konfirmasi', exact: true })).toBeDisabled();
  await story('status');
  await expect(page.getByText('Terkonfirmasi', { exact: true })).toBeVisible();
  await story('formulir');
  await page.getByRole('combobox', { name: 'Fungsi', exact: true }).click();
  await page.getByRole('option', { name: 'Operasi Terminal BBM Balikpapan', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Fungsi', exact: true })).toHaveText('Operasi Terminal BBM Balikpapan');
  await expect(page.getByLabel('Nama vendor', { exact: true })).toBeDisabled();
  await story('tab');
  await page.getByRole('tab', { name: 'Dokumen', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('tab', { name: 'Dokumen', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('tab', { name: 'HEA & Leaderboard', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Persiapan HEA', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Harga Timpang', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Pasangan item', exact: true })).toBeVisible();
  await story('tabel-dan-filter');
  await expect(page.locator('#storybook-root tbody tr')).toHaveCount(12);
  await page.evaluate(() => document.fonts.ready);
  if (process.env.PRISM_VISUAL_CAPTURE === '1') {
    await expect(page).toHaveScreenshot('prism-storybook-long-table.png', { fullPage: true });
  }
  await page.getByRole('textbox', { name: 'Cari pengadaan', exact: true }).fill('fasilitas 12');
  await expect(page.locator('#storybook-root tbody tr')).toHaveCount(1);
  await page.getByRole('combobox', { name: 'Status dokumen' }).click();
  await page.getByRole('option', { name: 'Terkonfirmasi', exact: true }).click();
  await expect(page.locator('#storybook-root tbody tr')).toHaveCount(0);
  await story('unggah');
  await page.locator('input[type="file"]').first().setInputFiles({ name: 'story.pdf', mimeType: 'application/pdf', buffer: Buffer.from('independent story input') });
  await expect(page.getByRole('status').filter({ hasText: 'Berkas dipilih:' })).toHaveText('Berkas dipilih: story.pdf');
  await story('progres');
  await expect(page.getByRole('navigation', { name: 'Progres evaluasi', exact: true })).toHaveCount(3);
  await expect(page.locator('#storybook-root .step:last-child')).toHaveText([/Hasil/, /Hasil/, /Hasil/]);
  await story('dialog');
  await page.getByRole('button', { name: 'Konfirmasi dokumen', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Konfirmasi data dokumen' })).toBeVisible();
  await page.keyboard.press('Tab');
  expect(await page.getByRole('dialog').evaluate(element => element.contains(document.activeElement))).toBe(true);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Konfirmasi dokumen', exact: true })).toBeFocused();
  await story('bukti-sumber');
  await expect(page.getByRole('heading', { name: 'Jejak sumber', exact: true })).toBeVisible();
  await story('kosong-dan-gagal');
  await page.getByRole('button', { name: 'Coba lagi', exact: true }).click();
  await expect(page.getByText('Memeriksa ulang dokumen…', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
  await info.attach('Storybook coverage', { body: '10 stories; Select, Tabs, long table filter, upload, dialog focus/Escape and retry interactions verified.', contentType: 'text/plain' });
});
