test("OE replacement survives failure, requires review, preserves old evidence and supports an empty procurement", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/pengadaan/proc-showcase?tab=dokumen");
  const card = page.locator(".fernly-upload");
  const oldReview = await card.getByRole("link", { name: "Lihat", exact: true }).getAttribute("href");
  await card.getByRole("link", { name: "Lihat", exact: true }).click();
  await page.getByRole("button", { name: "Kembali ke pengadaan", exact: true }).click();
  await card.getByRole("button", { name: "Ganti OE", exact: true }).click();
  const replacement = page.getByRole("dialog", { name: "Ganti Owner Estimate (OE)" });
  await expect(replacement).toBeVisible();
  await expect(card.getByRole("button", { name: "Ganti OE", exact: true, includeHidden: true })).toBeVisible();
  await capture(page, info, "documents-replace");
  await expect(replacement.getByRole("heading")).toContainText("Ganti Owner Estimate (OE)");
  await expect(replacement.getByRole("heading").locator("svg")).toHaveCount(1);
  await expect(replacement.getByRole("button", { name: "Tutup", exact: true })).toHaveCount(0);
  const zone = await replacement.locator(".upload-zone").boundingBox();
  const chooserPromise = page.waitForEvent("filechooser");
  await page.mouse.click(zone!.x + 16, zone!.y + 16);
  const chooser = await chooserPromise;
  await chooser.setFiles({ name: "invalid.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: Buffer.from("invalid") });
  await expect(page.getByRole("alert")).toBeVisible();
  await expect(card).toContainText("OE-Terminal.xlsx");
  const zoneBounds = await replacement.locator(".upload-zone").boundingBox();
  const errorBounds = await replacement.getByRole("alert").boundingBox();
  expect(errorBounds!.y - (zoneBounds!.y + zoneBounds!.height)).toBeGreaterThanOrEqual(16);
  await capture(page, info, "documents-replace-error");
  await page.getByRole("dialog", { name: "Ganti Owner Estimate (OE)" }).getByRole("button", { name: "Tutup ganti OE" }).click();
  await expect(page.getByRole("alert")).toHaveCount(0);
  await expect(page.getByLabel("Pilih berkas OE terbaru", { exact: true })).toHaveCount(0);
  await card.getByRole("button", { name: "Ganti OE", exact: true }).click();
  await page.getByLabel("Pilih berkas OE terbaru", { exact: true }).setInputFiles({ name: "OE-Terbaru.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: await readFile(path.resolve("public/files/OE-Terminal.xlsx")) });
  await expect(page).toHaveURL(/\/review\/doc-/);
  await expect(page.locator(".oe-review-header")).toContainText("OE-Terbaru.xlsx");
  await expect(page.locator(".oe-review-header")).toContainText("Perlu ditinjau");
  await page.getByRole("button", { name: "Kembali ke pengadaan", exact: true }).click();
  await expect(card).toContainText("OE-Terbaru.xlsx");
  await expect(card.locator(".badge")).toHaveCount(0);
  await expect(page.getByLabel("Pilih berkas dokumen", { exact: true })).toHaveCount(0);
  await card.getByRole("link", { name: "Lihat", exact: true }).click();
  await page.getByRole("button", { name: "Konfirmasi Data", exact: true }).click();
  await expect(page.getByText("Terkonfirmasi", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Kembali ke pengadaan", exact: true }).click();
  await expect(card.locator(".badge")).toHaveCount(0);
  // Browser Back preserves the in-memory runtime and the archived source.
  for (let step = 0; step < 6 && !page.url().endsWith(oldReview!); step++) await page.goBack();
  await expect(page).toHaveURL(new RegExp(`${oldReview}$`));
  await expect(page.getByText("Data ditampilkan sebagai arsip", { exact: false })).toBeVisible();
  await expect(page.getByRole("button", { name: "Edit OE", exact: true })).toBeDisabled();
  await expect(page.getByRole("treegrid")).toBeVisible();
  await page.goto("/pengadaan/proc-tank?tab=dokumen");
  await expect(page.getByRole("heading", { name: "Unggah Owner Estimate (OE)", exact: true })).toBeVisible();
  await expect(page.getByLabel("Pilih berkas dokumen", { exact: true })).toHaveAttribute("accept", ".xlsx");
  expect(errors).toEqual([]);
});

test("vendor document dialog supports available, mixed and empty slots and returns from review", async ({ page }, info) => {
  await page.goto("/pengadaan/proc-showcase?tab=ringkasan");
  const openNusa = page.getByRole("link", { name: "PT Nusa Teknik Mandiri · Buka dokumen", exact: true });
  await openNusa.click();
  let dialog = page.getByRole("dialog", { name: "Pilih Dokumen", exact: true });
  await expect(dialog.getByRole("link", { name: "Buka Form A5", exact: true })).toBeVisible();
  await expect(dialog.getByRole("link", { name: "Buka Penawaran Harga", exact: true })).toBeVisible();
  await expect(dialog.locator('input[type="file"]')).toHaveCount(0);
  await expect(dialog).not.toHaveAttribute("aria-describedby");
  const divider = await dialog.locator(":scope > h2").evaluate(element => {
    const style = getComputedStyle(element, "::after");
    return { left: parseFloat(style.left), width: parseFloat(style.width), headingWidth: element.getBoundingClientRect().width };
  });
  expect(divider.left).toBe(0);
  expect(Math.abs(divider.width - divider.headingWidth)).toBeLessThan(1);
  await expect(dialog.getByRole("heading", { name: "Pilih Dokumen", exact: true })).toHaveCSS("text-align", "center");
  await expect(dialog.getByRole("button", { name: "Tutup", exact: true })).toHaveCount(0);
  await expect(dialog.locator(".vendor-document-caption > span").first()).toHaveText("Buka");
  await capture(page, info, "vendor-documents-available");
  await dialog.getByRole("link", { name: "Buka Form A5", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Form-A5-Nusa.pdf", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Kembali ke pengadaan", exact: true }).click();
  await expect(dialog).toBeVisible();
  await dialog.getByRole("button", { name: "Tutup dokumen vendor", exact: true }).click();
  await page.getByRole("button", { name: "Tabel", exact: true }).click();
  const borneoRow = page.getByRole("row").filter({ hasText: "PT Borneo Teknik Nusantara" });
  await expect(borneoRow.locator(".vendor-documents-cell > svg")).toHaveCount(1);
  await borneoRow.locator("td").nth(1).scrollIntoViewIfNeeded();
  const dateCell = await borneoRow.locator("td").nth(1).boundingBox();
  await page.mouse.click(dateCell!.x + dateCell!.width / 2, dateCell!.y + dateCell!.height / 2);
  dialog = page.getByRole("dialog", { name: "Pilih Dokumen", exact: true });
  await expect(dialog.getByRole("link", { name: "Buka Form A5", exact: true })).toBeVisible();
  await expect(dialog.getByLabel("Unggah Penawaran Harga", { exact: true })).toHaveAttribute("accept", ".xlsx");
  await capture(page, info, "vendor-documents-mixed");
  await dialog.getByRole("button", { name: "Tutup dokumen vendor", exact: true }).click();
  await page.getByRole("button", { name: "Tambah vendor", exact: true }).click();
  await page.getByRole("button", { name: "Isi nama vendor secara manual", exact: true }).click();
  await page.getByLabel("Nama badan usaha").fill("Vendor Dokumen Baru");
  await page.getByRole("dialog", { name: "Tambah vendor", exact: true }).getByRole("button", { name: "Tambah vendor", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Tambah vendor", exact: true })).toHaveCount(0);
  await page.getByRole("link", { name: "Vendor Dokumen Baru · Buka dokumen", exact: true }).focus();
  await page.keyboard.press("Space");
  dialog = page.getByRole("dialog", { name: "Pilih Dokumen", exact: true });
  await expect(dialog.getByLabel("Unggah Form A5", { exact: true })).toHaveAttribute("accept", ".pdf");
  await expect(dialog.getByLabel("Unggah Penawaran Harga", { exact: true })).toHaveAttribute("accept", ".xlsx");
  await capture(page, info, "vendor-documents-empty");
  await dialog.getByLabel("Unggah Form A5", { exact: true }).setInputFiles({ name: "invalid.pdf", mimeType: "application/pdf", buffer: Buffer.from("invalid") });
  await expect(dialog.getByRole("alert")).toBeVisible();
  await dialog.getByLabel("Unggah Form A5", { exact: true }).setInputFiles(path.resolve("public/files/Form-A5-Nusa.pdf"));
  await expect(page).toHaveURL(/\/review\/doc-/);
  await page.getByRole("button", { name: "Kembali ke pengadaan", exact: true }).click();
  await expect(dialog.getByRole("link", { name: "Buka Form A5", exact: true })).toBeVisible();
  await dialog.getByLabel("Unggah Penawaran Harga", { exact: true }).setInputFiles(path.resolve("public/files/Penawaran-Nusa.xlsx"));
  await expect(page.locator(".review-document-identity")).toContainText("Penawaran-Nusa.xlsx");
  await page.getByRole("button", { name: "Kembali ke pengadaan", exact: true }).click();
  await expect(dialog.getByRole("link", { name: "Buka Penawaran Harga", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await page.goto("/pengadaan/proc-showcase/vendor/showcase-nusa");
  await expect(page).toHaveURL(/tab=ringkasan&vendor=showcase-nusa/);
  await expect(page.getByRole("dialog", { name: "Pilih Dokumen", exact: true })).toBeVisible();
});
