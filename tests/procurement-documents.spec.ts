import { expect, test } from "@playwright/test";
import type { Page, TestInfo } from "@playwright/test";
import { readFile } from "node:fs/promises";
import path from "node:path";

async function capture(page: Page, info: TestInfo, name: string) {
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: info.outputPath(`${name}.png`), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
}

test("OE card and vendor layouts keep review links, document availability and real addition dates", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/pengadaan/proc-showcase?tab=dokumen");
  await expect(page.getByRole("heading", { name: "Penggantian Jalur Pipa", exact: true })).toBeVisible();
  await expect(page.locator(".procurement-heading-meta > div")).toHaveCount(4);
  await expect(page.locator(".procurement-heading-meta dd svg")).toHaveCount(4);
  await expect(page.getByRole("heading", { name: "Owner Estimate (OE)", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Identitas pengadaan", exact: true })).toHaveCount(0);
  await expect(page.locator(".procurement-heading-meta time")).toHaveAttribute("datetime", "2026-10-02T09:00:00+07:00");
  await expect(page.locator(".procurement-identity-summary")).toHaveCount(0);
  const addButton = await page.getByRole("button", { name: "Tambah vendor", exact: true }).boundingBox();
  const tableToggle = await page.getByRole("button", { name: "Tabel", exact: true }).boundingBox();
  expect(addButton!.x + addButton!.width).toBeGreaterThanOrEqual(tableToggle!.x + tableToggle!.width);
  await expect(page.locator(".owner-estimate-document")).toContainText("OE-Terminal.xlsx");
  await expect(page.getByRole("navigation", { name: "Tahap pengadaan" }).getByRole("button")).toHaveCount(2);
  await expect(page.getByRole("button", { name: /Unggah & verifikasi/ })).toHaveCount(0);
  await expect(page.locator(".owner-estimate-document .badge")).toHaveCount(0);
  await expect(page.locator(".owner-estimate-uploaded")).not.toContainText("Revisi");
  await expect(page.locator(".procurement-vendor-card").first().getByLabel("Form A5: tersedia")).toHaveCSS("color", "rgb(34, 99, 63)");
  await expect(page.locator(".procurement-vendor-card").last().getByLabel("Penawaran Harga: belum tersedia")).toHaveCSS("color", "rgb(162, 43, 32)");
  await expect(page.getByRole("heading", { name: "Dokumen OE", exact: true })).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Daftar Dokumen Vendor", exact: true })).toHaveCount(0);
  await capture(page, info, "documents-grid");
  const switcher = page.getByRole("group", { name: "Tampilan daftar vendor" });
  await switcher.getByRole("button", { name: "Tabel", exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(switcher.getByRole("button", { name: "Tabel", exact: true })).toHaveAttribute("aria-pressed", "true");
  const table = page.getByRole("table", { name: "vendor", exact: true });
  const nusa = table.getByRole("row").filter({ hasText: "PT Nusa Teknik Mandiri" });
  const borneo = table.getByRole("row").filter({ hasText: "PT Borneo Teknik Nusantara" });
  await expect(nusa.getByLabel("Form A5: tersedia")).toHaveClass(/success/);
  await expect(nusa.getByLabel("Penawaran Harga: tersedia")).toHaveClass(/success/);
  await expect(borneo.getByLabel("Penawaran Harga: belum tersedia")).toHaveClass(/error/);
  const heading = await page.locator(".vendor-collection-header").boundingBox();
  const tableBounds = await table.boundingBox();
  expect(tableBounds!.y - heading!.y - heading!.height).toBeLessThanOrEqual(24);
  const headers = await table.getByRole("columnheader").all();
  const cells = await nusa.getByRole("cell").all();
  for (let column = 0; column < headers.length; column++) {
    const headerBox = await headers[column].boundingBox();
    const cellBox = await cells[column].boundingBox();
    expect(Math.abs(headerBox!.x - cellBox!.x)).toBeLessThan(1);
    expect(Math.abs(headerBox!.width - cellBox!.width)).toBeLessThan(1);
  }
  await capture(page, info, "documents-table");
  await table.getByRole("link", { name: "PT Nusa Teknik Mandiri · Buka dokumen" }).click();
  await expect(page).toHaveURL(/vendor=showcase-nusa/);
  await expect(page.getByRole("dialog", { name: "Pilih Dokumen", exact: true })).toBeVisible();
  await page.goto("/pengadaan/proc-showcase?tab=ringkasan");
  await page.getByRole("button", { name: "Tambah vendor", exact: true }).click();
  await page.getByRole("button", { name: "Isi nama vendor secara manual", exact: true }).click();
  await page.getByLabel("Nama badan usaha").fill("Vendor Baru Review");
  await page.getByRole("dialog", { name: "Tambah vendor" }).getByRole("button", { name: "Tambah vendor", exact: true }).click();
  await page.getByRole("button", { name: "Tabel", exact: true }).click();
  const added = page.getByRole("table", { name: "vendor", exact: true }).getByRole("row").filter({ hasText: "Vendor Baru Review" });
  await expect(added.locator("time")).toHaveAttribute("datetime", /^\d{4}-\d{2}-\d{2}T/);
  await expect(added.getByLabel("Form A5: belum tersedia")).toHaveClass(/error/);
  await expect(added.getByLabel("Penawaran Harga: belum tersedia")).toHaveClass(/error/);
  expect(errors).toEqual([]);
});

