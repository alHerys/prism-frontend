import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, expect, it } from "vitest";
import { createTestSession } from "../../../infrastructure/local/test-session";
import { createLocalRuntime } from "../../../infrastructure/local/runtime";
import { createApplication } from "../../../app/bootstrap/application";
import { ApplicationProviders } from "../../../app/providers/ApplicationProviders";
import BankPage from "./BankPage";
afterEach(cleanup);
it("uses every reference in the requested unit without manual selection or comparability edits", async () => {
  const runtime = createLocalRuntime(), service = createTestSession(true, false, runtime);
  const before = structuredClone(service.getState().historicalItems);
  render(<ApplicationProviders application={createApplication(runtime)}><BankPage /></ApplicationProviders>);
  expect(screen.queryByRole("tab")).not.toBeInTheDocument();
  expect(screen.queryByRole("checkbox")).not.toBeInTheDocument();
  expect(screen.getByText("3 referensi dengan satuan m² digunakan otomatis.")).toBeInTheDocument();
  await userEvent.type(screen.getByLabelText("Uraian pekerjaan"), "Pengecatan dinding");
  await userEvent.type(screen.getByLabelText("Kuantitas"), "17");
  await userEvent.click(screen.getByRole("button", { name: "Buat estimasi" }));
  await screen.findByRole("heading", { name: "Hasil estimasi · Pengecatan dinding" });
  expect(service.getState().estimates[0]).toMatchObject({ total: "1530000", referenceIds: before.map(item => item.id) });
  expect(service.getState().historicalItems).toEqual(before);
});
it("handles missing units and retains an earlier result after invalid quantity", async () => {
  const runtime = createLocalRuntime(true, true), service = createTestSession(true, false, runtime);
  const before = structuredClone(service.getState().estimates);
  render(<ApplicationProviders application={createApplication(runtime)}><BankPage /></ApplicationProviders>);
  fireEvent.change(screen.getByLabelText("Satuan"), { target: { value: "unit" } });
  expect(screen.getByText("0 referensi dengan satuan unit digunakan otomatis.")).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "Buat estimasi" })).toBeDisabled();
  fireEvent.change(screen.getByLabelText("Satuan"), { target: { value: "m²" } });
  fireEvent.change(screen.getByLabelText("Kuantitas"), { target: { value: "invalid" } });
  await userEvent.click(screen.getByRole("button", { name: "Buat estimasi" }));
  await waitFor(() => expect(screen.getByRole("alert")).toHaveTextContent("angka desimal"));
  expect(screen.getByLabelText("Kuantitas")).toHaveValue("invalid");
  expect(service.getState().estimates).toEqual(before);
});
